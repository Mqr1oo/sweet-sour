-- ---------------------------------------------------------------- triggere comenzi
create or replace function public.sanitize_comanda_insert()
returns trigger language plpgsql set search_path = 'public','pg_temp' as $$
begin
  if auth.role() = 'anon' or auth.uid() is null then
    NEW.status := 'noua'; NEW.bon_scos := false;
    NEW.comp_motiv := null; NEW.comp_de := null;
    NEW.preluat_de := null; NEW.creat_de := null;
    NEW.confirmada_la := null; NEW.created_at := now();
  else
    if NEW.creat_de is not null then
      NEW.creat_de := (select auth.jwt() ->> 'email');
    end if;
    NEW.created_at := now();
  end if;
  return NEW;
end; $$;

create or replace function public.recalculeaza_total_comanda()
returns trigger language plpgsql security definer set search_path = 'public','pg_temp' as $$
declare
  v_item jsonb; v_items jsonb := '[]'::jsonb; v_total numeric(10,2) := 0;
  v_qty numeric; v_nume text; v_id text; v_pret numeric(10,2);
  v_variabil boolean; v_pret_client numeric; v_gasit boolean;
begin
  if jsonb_typeof(NEW.produse) <> 'array' then
    raise exception 'Campul produse trebuie sa fie o lista.';
  end if;

  for v_item in select * from jsonb_array_elements(NEW.produse) loop
    v_nume := coalesce(v_item ->> 'nume', '');
    v_qty  := coalesce((v_item ->> 'cantitate')::numeric, 0);
    v_id   := nullif(v_item ->> 'id_produs', '');

    -- notele clientului si alertele de ospatar nu sunt produse: raman la 0
    if v_qty <= 0 or v_nume like '📝%' or v_nume like '🔔%'
       or v_nume like '%ALERTĂ OSPĂTAR%' then
      v_items := v_items || jsonb_build_array(v_item || jsonb_build_object('pret_unitar', 0));
      continue;
    end if;

    if v_qty > 50 then
      raise exception 'Cantitate nerezonabila pentru "%": %', v_nume, v_qty;
    end if;

    v_gasit := false;
    if v_id is not null then
      select pret, pret_variabil into v_pret, v_variabil
      from public.meniu_produse where id_produs = v_id;
      v_gasit := found;
    end if;
    if not v_gasit then
      select pret, pret_variabil into v_pret, v_variabil
      from public.meniu_produse
      where lower(btrim(v_nume)) = any (nume_variante) limit 1;
      v_gasit := found;
    end if;
    if not v_gasit then
      raise exception 'Produs inexistent in meniu: "%"', v_nume;
    end if;

    if v_variabil then
      v_pret_client := coalesce((v_item ->> 'pret_unitar')::numeric, 0);
      if v_pret_client < 0 or v_pret_client > 1000 then
        raise exception 'Pret invalid pentru produsul cu pret variabil "%"', v_nume;
      end if;
      v_pret := round(v_pret_client, 2);
    end if;

    v_total := v_total + (v_pret * v_qty);
    v_items := v_items || jsonb_build_array(v_item || jsonb_build_object('pret_unitar', v_pret));
  end loop;

  NEW.produse := v_items;
  NEW.total   := round(v_total, 2);
  return NEW;
end; $$;

create or replace function public.protect_comanda_update()
returns trigger language plpgsql security definer set search_path = 'public','pg_temp' as $$
declare v_rol text; v_uid uuid := (select auth.uid());
begin
  if v_uid is null then return NEW; end if;   -- cron / mentenanta server-side
  select rol into v_rol from public.staff_roles where uid = v_uid;
  if v_rol is null then
    raise exception 'Acces interzis: utilizatorul nu este inregistrat in staff_roles.';
  end if;
  if v_rol <> 'director' then
    if NEW.produse is distinct from OLD.produse
    or NEW.total is distinct from OLD.total
    or NEW.mesa is distinct from OLD.mesa
    or NEW.sectiune is distinct from OLD.sectiune
    or NEW.grup_comanda is distinct from OLD.grup_comanda
    or NEW.created_at is distinct from OLD.created_at then
      raise exception 'Doar directorul poate modifica produsele, totalul sau masa unei comenzi.';
    end if;
  end if;
  if NEW.preluat_de is distinct from OLD.preluat_de and NEW.preluat_de is not null then
    NEW.preluat_de := (select auth.jwt() ->> 'email');
  end if;
  if NEW.comp_de is distinct from OLD.comp_de and NEW.comp_de is not null then
    NEW.comp_de := (select auth.jwt() ->> 'email');
  end if;
  return NEW;
end; $$;

create or replace function public.enforce_bon_scos_bar_only()
returns trigger language plpgsql security definer set search_path = 'public','pg_temp' as $$
declare v_rol text; v_uid uuid := (select auth.uid());
begin
  if NEW.bon_scos is distinct from OLD.bon_scos and v_uid is not null then
    select rol into v_rol from public.staff_roles where uid = v_uid;
    if v_rol is distinct from 'bar' and v_rol is distinct from 'director' then
      raise exception 'Doar personalul de la bar poate confirma bonul.';
    end if;
  end if;
  return NEW;
end; $$;

create or replace function public.split_takeaway_contact()
returns trigger language plpgsql security definer set search_path = 'public','pg_temp' as $$
declare v_rest text; v_nume text; v_tel text;
begin
  if NEW.mesa is not null and NEW.mesa like '%Tk:%' then
    v_rest := btrim(split_part(NEW.mesa, 'Tk:', 2));
    v_nume := btrim(split_part(v_rest, '/', 1));
    v_tel  := btrim(split_part(v_rest, '/', 2));
    insert into public.contacte_takeaway (comanda_id, nume, telefon)
    values (NEW.id, nullif(v_nume,''), nullif(v_tel,''))
    on conflict (comanda_id) do update
      set nume = excluded.nume, telefon = excluded.telefon;
    -- coloana `mesa` ramane fara date personale
    update public.comenzi set mesa = '🥡 La pachet' where id = NEW.id;
  end if;
  return NEW;
end; $$;

create or replace function public.force_jurnal_utilizator()
returns trigger language plpgsql set search_path = 'public','pg_temp' as $$
begin
  if auth.uid() is null then NEW.utilizator := 'client';
  else NEW.utilizator := coalesce((select auth.jwt() ->> 'email'), 'staff');
  end if;
  NEW.created_at := now();
  return NEW;
end; $$;

create or replace function public.push_forteaza_rol()
returns trigger language plpgsql security definer set search_path = 'public','pg_temp' as $$
begin
  select rol into NEW.rol from public.staff_roles where uid = NEW.uid;
  if NEW.rol is null then
    raise exception 'Utilizatorul nu are rol in staff_roles.';
  end if;
  return NEW;
end; $$;

