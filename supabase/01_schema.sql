-- is_staff() si current_staff_rol() TREBUIE sa ramana apelabile de `authenticated`:
-- politicile RLS se evalueaza cu drepturile apelantului, deci fara EXECUTE s-ar
-- bloca tot dashboard-ul. Nu sunt periculoase — raspund doar despre utilizatorul
-- care intreaba. Le luam insa de la `anon`, care n-are nicio politica ce le foloseste.
revoke all on function public.is_staff()          from public, anon;
revoke all on function public.current_staff_rol() from public, anon;
grant execute on function public.is_staff()          to authenticated;
grant execute on function public.current_staff_rol() to authenticated;

-- Functiile viitoare nu mai primesc EXECUTE automat.
alter default privileges in schema public revoke execute on functions from public, anon;

