create or replace function public.auto_free_tables()
returns void language plpgsql security definer set search_path = 'public' as $$
declare freed_mesas text[];
begin
  with candidates as (
    select o.mesa, max(o.confirmada_la) as last_confirm
    from comenzi o
    where o.status = 'finalizata' and o.confirmada_la is not null
      and exists (
        select 1 from jsonb_array_elements(o.produse) p
        where p->>'nume' ilike '%ALERT%'
          and (p->>'nume') ~* '(Cash|Card|Numerar|Efectivo|Esp[eè]ces|Carte)'
      )
    group by o.mesa
  ),
  to_free as (
    select c.mesa, c.last_confirm from candidates c
    where now() - c.last_confirm >= interval '15 minutes'
      and not exists (
        select 1 from jurnal_activitate j
        where j.actiune = 'mesa_liberada'
          and j.detalii->>'mesa' = c.mesa
          and j.created_at > c.last_confirm
      )
  ),
  inserted as (
    insert into jurnal_activitate (utilizator, actiune, comanda_id, detalii, created_at)
    select 'sistema', 'mesa_liberada', null,
           jsonb_build_object('mesa', mesa, 'automat', true), now()
    from to_free
    returning detalii->>'mesa' as mesa
  )
  select array_agg(mesa) into freed_mesas from inserted;

  if freed_mesas is not null then
    delete from comenzi o
    where o.mesa = any(freed_mesas)
      and o.status in ('finalizata','noua')
      and exists (
        select 1 from jsonb_array_elements(o.produse) p where p->>'nume' ilike '%ALERT%'
      );
  end if;
end; $$;

-- Inchiderea de la miezul noptii, pe fusul orar al Romaniei.
create or replace function public.curatare_mese_miezul_noptii()
returns void language plpgsql security definer set search_path = 'public' as $$
declare
  data_ro text := to_char((now() at time zone 'utc') at time zone 'Europe/Bucharest', 'YYYY-MM-DD');
  ora_ro  int  := extract(hour from ((now() at time zone 'utc') at time zone 'Europe/Bucharest'));
  deja_rulat boolean; cfg jsonb; zona jsonb; masa jsonb;
begin
  if ora_ro <> 0 then return; end if;

  select exists (
    select 1 from jurnal_activitate
    where actiune = 'curatare_miezul_noptii' and detalii->>'data' = data_ro
  ) into deja_rulat;
  if deja_rulat then return; end if;

  select detalii into cfg from jurnal_activitate
  where actiune = 'config_mese' order by created_at desc limit 1;

  if cfg is not null and cfg ? 'zones' then
    for zona in select jsonb_array_elements(cfg->'zones') loop
      for masa in select jsonb_array_elements(zona->'mese') loop
        insert into jurnal_activitate (utilizator, actiune, comanda_id, detalii)
        values ('sistema', 'mesa_liberada', null,
                jsonb_build_object('mesa', masa->>'numar', 'automat', true,
                                   'motiv', 'inchidere_miezul_noptii'));
      end loop;
    end loop;
  end if;

  insert into jurnal_activitate (utilizator, actiune, comanda_id, detalii)
  values ('sistema', 'curatare_miezul_noptii', null, jsonb_build_object('data', data_ro));
end; $$;

