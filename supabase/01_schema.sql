-- DUPA rulare, mai ai de facut manual (nu se pot automatiza din SQL):
--
-- 1. Authentication -> Providers -> Email: dezactiveaza "Enable sign-ups".
--    Conturile de personal se creeaza doar de tine, din consola.
-- 2. Authentication -> Policies: activeaza "Leaked password protection"
